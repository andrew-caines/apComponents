import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import { INPUT_TOKENS } from '../components/Input/Input.tokens.js'
import { FIELD_TOKENS } from '../components/Field/Field.tokens.js'

const PAGE = join(import.meta.dirname, '../../../../examples/InputFields.html')

/**
 * `examples/InputFields.html` is generated and committed, and unlike
 * `theme.css` it cannot be byte-compared here: regenerating it needs a Vite
 * build and a browser, which is far too heavy for the unit suite.
 *
 * So this gate covers the one part of the page that is a *claim about the
 * library* rather than a rendering of it — the Tier 3 override table. That
 * table tells a consumer which custom properties exist and what each falls
 * back to. Adding, renaming or re-pointing a Tier 3 token without regenerating
 * leaves the page confidently documenting an API that is gone, and nothing
 * else in the suite would notice: the components would still render, the
 * screenshots would still look right, and the only symptom would be a product
 * setting a custom property that does nothing.
 *
 * Everything else on that page is derived at generation time from a real
 * render and a real vanilla-extract compile, and `npm run gen:input-demo`'s own
 * six browser checks are what guard it. This is deliberately the narrow half
 * that is both cheap to check and expensive to get wrong.
 */
describe('gate: the committed Input/Field examples page documents the real Tier 3 tokens', () => {
  const html = readFileSync(PAGE, 'utf8')

  it('finds the generated page', () => {
    expect(html).toContain('GENERATED by <code>scripts/gen-input-demo.ts</code>')
  })

  const cases = [
    ...Object.entries(INPUT_TOKENS).map(([key, value]) => ['Input', key, value] as const),
    ...Object.entries(FIELD_TOKENS).map(([key, value]) => ['Field', key, value] as const),
  ]

  it.each(cases)('documents %s.%s with its current fallback', (_component, key, value) => {
    // The key and the resolved `var(--ap-…, var(--ap-…))` string are asserted
    // together, in one row. Asserting only the key would keep passing after a
    // token was re-pointed at a different Tier 2 fallback — which is the more
    // likely edit and the more misleading page.
    const row = `<td class="mono">${key}</td><td class="mono dim">${value
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')}</td>`
    expect(
      html,
      `examples/InputFields.html has no row for "${key}" resolving to "${value}" — ` +
        'the page is stale. Run `npm run gen:input-demo` and commit the result.',
    ).toContain(row)
  })

  it('documents no token that no longer exists', () => {
    // The other direction: a REMOVED token leaves a row behind, and every
    // per-token assertion above still passes, because each only looks for its
    // own row. Counting is what closes that.
    const rows = html.match(/<td class="mono">[a-zA-Z]+<\/td><td class="mono dim">var\(/g) ?? []
    expect(
      rows.length,
      'the page lists a different number of Tier 3 tokens than the components declare — ' +
        'a token was probably removed. Run `npm run gen:input-demo` and commit the result.',
    ).toBe(cases.length)
  })
})
