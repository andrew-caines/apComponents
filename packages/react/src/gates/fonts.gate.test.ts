import { existsSync, readFileSync, statSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import { DEFAULT_BRAND, generateTheme, toFallbackFontFaceCss } from '@ap/tokens'
import {
  loadFontSubsetSource,
  normalizeUnicodeRange,
  pickFile,
  unicodeRangeFor,
} from '../theme/font-subsets.js'

const ROOT = join(import.meta.dirname, '../..')
const FONTS_CSS = join(ROOT, 'src/theme/fonts.css')

describe('gate: fonts', () => {
  const css = readFileSync(FONTS_CSS, 'utf8')

  it('vendors both woff2 subsets with plausible sizes', () => {
    for (const f of ['inter-latin.woff2', 'inter-latin-ext.woff2']) {
      const p = join(ROOT, 'fonts', f)
      expect(existsSync(p), `${f} missing`).toBe(true)
      expect(statSync(p).size).toBeGreaterThan(10_000)
    }
  })

  it('references the vendored files by relative path, never a remote URL', () => {
    expect(css).toContain("url('../../fonts/inter-latin.woff2')")
    expect(css).toContain("url('../../fonts/inter-latin-ext.woff2')")
    expect(css).not.toMatch(/https?:\/\//)
    expect(css).not.toMatch(/url\(\s*['"]?\/\//)
    expect(css).not.toMatch(/url\(\s*['"]?data:/)
  })

  it('emits the metric-matched fallback face verbatim from the token engine', () => {
    expect(css).toContain(toFallbackFontFaceCss(generateTheme({ brand: DEFAULT_BRAND })))
  })

  it('uses font-display: swap on the real faces', () => {
    expect(css.match(/font-display: swap;/g)?.length).toBe(2)
  })

  it('carries the do-not-edit header naming the regen command', () => {
    expect(css).toContain('GENERATED by scripts/gen-fonts.ts')
    expect(css).toContain('npm run gen:fonts')
  })

  it('declares exactly the unicode-range upstream ships for each vendored file', () => {
    const { filesDir, available, wghtCss } = loadFontSubsetSource()
    const subsets = [
      { file: pickFile(available, /^inter-latin-wght-normal\.woff2$/, filesDir) },
      { file: pickFile(available, /^inter-latin-ext-wght-normal\.woff2$/, filesDir) },
    ]
    const declared = [...css.matchAll(/unicode-range:\s*([^;]+);/g)].map((m) =>
      normalizeUnicodeRange(m[1]!),
    )
    for (const s of subsets) {
      const expected = normalizeUnicodeRange(unicodeRangeFor(wghtCss, s.file))
      expect(
        declared,
        `fonts.css does not declare upstream's unicode-range for ${s.file} — run \`npm run gen:fonts\` and commit the result`,
      ).toContain(expected)
    }
  })

  it('declares honest variable-font metadata on both real faces', () => {
    expect(css.match(/font-weight: 100 900;/g)?.length).toBe(2)
    expect(css.match(/format\('woff2-variations'\)/g)?.length).toBe(2)
  })
})
